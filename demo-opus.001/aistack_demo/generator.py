def _readme(rec: dict, model_label: str) -> str:
    rows = "\n".join(
        f"| {l['friendly']} | {l['state']} | {l['component'] or '-'} | {l['rationale']} |"
        for l in rec["layers"])
    return f"""# Fusion Fuel

Quick fusion recipes that fit a carbohydrate target, for a physically active person managing diabetes.
Generated by AiStackE2E demo-opus.001 on {datetime.now(timezone.utc):%Y-%m-%d}. Model: {model_label}.

> Not medical advice. Carbohydrate values come from an approximate demo table; replace it with a
> verified source (e.g. USDA FoodData Central) before real use.

## Run

```bash
uv sync
uv run pytest                      # offline; uses the simulated fixture model
export ANTHROPIC_API_KEY=...       # or OPENAI_API_KEY, matching aistack.yaml
uv run uvicorn fusion_fuel.api:app --app-dir src --reload
curl -X POST localhost:8000/recipes -H 'content-type: application/json' \\
  -d '{{"cuisines":["korean","mexican"],"carb_target_g":45,"activity":"post_workout"}}'
```

## Architecture (why each layer is here, or not)

| Layer | State | Component | Rationale |
| --- | --- | --- | --- |
{rows}

Diagrams: `docs/architecture.md`. Architecture source of truth: `aistack.yaml`.
"""


AGENTS_MD = """# Guidance for coding agents

- `aistack.yaml` is the architecture source of truth. Change it first, then regenerate.
- Files starting with `# aistack: managed` are owned by the generator; edit `pipeline.py` business logic
  freely but keep the contracts in `contracts.py` stable (bump the version on breaking changes).
- Carbohydrate numbers must come from `nutrition.py`, never from the model.
- Dosing or medication questions must stay blocked by `guards.py`.
"""


def build_zip(rec: dict, prd_text: str = "") -> bytes:
    manifest = rec["manifest"]
    model_key = manifest["layers"]["model"]["config"]["modelKey"]
    entry = prices()["models"][model_key]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        root = "fusion-fuel/"
        z.writestr(root + "aistack.yaml", yaml.safe_dump(manifest, sort_keys=False, width=100))
        z.writestr(root + "README.md", _readme(rec, entry["label"]))
        z.writestr(root + "AGENTS.md", AGENTS_MD)
        if prd_text.strip():
            z.writestr(root + "docs/PRD.md", "# Product requirements\n\n" + prd_text.strip() + "\n")
        z.writestr(root + "pyproject.toml", PYPROJECT)
        z.writestr(root + "Dockerfile", DOCKERFILE)
        z.writestr(root + ".env.example", "ANTHROPIC_API_KEY=\nOPENAI_API_KEY=\n")
        z.writestr(root + "docs/architecture.md",
                   "# Architecture\n\n## Beginner\n\n```mermaid\n" + BEGINNER_DIAGRAM +
                   "\n```\n\n## Advanced\n\n```mermaid\n" +
                   ADVANCED_DIAGRAM.format(model=entry["label"]) + "\n```\n")
        pkg = root + "src/fusion_fuel/"
        z.writestr(pkg + "__init__.py", '"""Fusion Fuel - generated by AiStackE2E."""\n')
        for name in COPIED_MODULES:
            z.writestr(pkg + name, (PACKAGE / name).read_text())
        z.writestr(pkg + "settings.py", SETTINGS.format(provider=entry["provider"], model_id=entry["model_id"]))
        z.writestr(pkg + "api.py", API)
        z.writestr(root + "tests/test_pipeline.py", TESTS)
    return buf.getvalue()
