import yaml

from .config import PACKAGE, prices

COPIED_MODULES = ["contracts.py", "nutrition.py", "guards.py", "restrictions.py", "goals.py", "models.py", "pipeline.py"]

BEGINNER_DIAGRAM = """flowchart LR
  I[Input: meal request] --> M[Model: draft recipe] --> D{Decision: within carb target?}
  D -- yes --> V[Validate: schema and safety] --> R[Result: recipe card]
  D -- no --> A[Action: adjust with nutrition tool] --> V"""

